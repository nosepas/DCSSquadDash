"""Regenerate the hash-pinned lock files in requirements/ from pyproject.toml.

Usage (from the repo root, with uv installed in a throw-away venv or globally):
    python tools/lock_requirements.py [--upgrade]

The locks are universal (all platforms) and resolved for the lowest supported Python (3.12),
so a single file serves CI (3.12/3.13) and local development (3.14). Install with:
    pip install --require-hashes -r requirements/dev.txt
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PYTHON = "3.12"
# lock file -> extras of pyproject.toml it covers
LOCKS = {
    "central.txt": ["postgres"],
    "agent-build.txt": ["build"],
    "dev.txt": ["dev", "postgres"],
}


def main() -> int:
    upgrade = ["--upgrade"] if "--upgrade" in sys.argv[1:] else []
    for name, extras in LOCKS.items():
        out = f"requirements/{name}"
        cmd = [
            sys.executable, "-m", "uv", "pip", "compile", "pyproject.toml",
            "--universal", "--generate-hashes", "--python-version", PYTHON,
            "--no-header", "--quiet", "-o", out, *upgrade,
        ]  # fmt: skip
        for extra in extras:
            cmd += ["--extra", extra]
        print("->", out)
        if subprocess.run(cmd, cwd=ROOT, check=False).returncode:
            return 1
        path = ROOT / out
        path.write_text(f"# Generated by tools/lock_requirements.py - do not edit.\n{path.read_text()}", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
